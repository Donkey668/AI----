import { test,expect,devices } from '@playwright/test';
import { readFile } from 'node:fs/promises';
test.use({...devices['Pixel 5']});
test('login, refresh, create/edit/delete record, TXT download, logout',async({page})=>{
 const speciesName='迁移浏览器测试鸟'+Date.now();
 await page.goto('/');
 await page.getByRole('button',{name:'登录',exact:true}).filter({visible:true}).click();
 await page.getByLabel('助手账号',{exact:false}).fill('MIGRATION_A');
 await page.getByLabel('用户密码',{exact:false}).fill('wrong');
 await page.getByRole('dialog').getByRole('button',{name:'确认登录',exact:true}).click();
 await expect(page.getByText('用户密码错误。',{exact:true})).toBeVisible();
 await page.getByLabel('用户密码',{exact:false}).fill('MigrationTest1');
 await page.getByRole('dialog').getByRole('button',{name:'确认登录',exact:true}).click();
 await expect(page.getByRole('button',{name:'当前登录用户 @MIGRATION_A'}).filter({visible:true})).toBeVisible();
 await page.reload();
 await expect(page.getByRole('button',{name:'当前登录用户 @MIGRATION_A'}).filter({visible:true})).toBeVisible();
 await page.getByRole('button',{name:'个人观测记录',exact:true}).click();
 await page.getByRole('button',{name:'新增记录',exact:true}).click();
 await page.locator('#record-species-name').fill(speciesName);
 await page.locator('#record-bird-point').fill('独立测试鸟点');
 await page.locator('#record-note').fill('浏览器测试记录');
 const dialog=page.getByRole('dialog');
 await dialog.getByRole('button',{name:/^(新增|保存|添加)$/}).click();
 await expect(page.getByText(speciesName,{exact:true})).toBeVisible();
 const downloadEvent=page.waitForEvent('download');await page.getByRole('button',{name:'保存记录到本地'}).click();
 const download=await downloadEvent;expect(download.suggestedFilename()).toBe('MIGRATION_A的观鸟记录.txt');
 const path=await download.path();expect(await readFile(path!,'utf8')).toContain('鸟名：'+speciesName);
 await page.screenshot({path:'test-results/records.png'});
 await page.getByText(speciesName,{exact:true}).click();
 await page.locator('#record-note').fill('已编辑');await page.getByRole('dialog').getByRole('button',{name:'保存',exact:true}).click();
 await page.getByRole('button',{name:'删除 '+speciesName+' 记录',exact:true}).click();
 await page.getByRole('button',{name:'确认删除',exact:true}).click();
 await expect(page.getByText(speciesName,{exact:true})).toHaveCount(0);
 await page.getByRole('button',{name:'当前登录用户 @MIGRATION_A'}).filter({visible:true}).click();
 await page.getByRole('menuitem',{name:'退出登录'}).click();
 await expect(page.getByRole('button',{name:'登录',exact:true}).filter({visible:true})).toBeVisible();
});
